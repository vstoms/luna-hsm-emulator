def ckr_name(code: int) -> str:
    """Return the symbolic name for a CKR_ return code."""
    return CKR_NAMES.get(code, f"UNKNOWN(0x{code:08X})")


def cka_name(attr: int) -> str:
    """Return the symbolic name for a CKA_ attribute."""
    return CKA_NAMES.get(attr, f"UNKNOWN(0x{attr:08X})")


def ckm_name(mech: int) -> str:
    """Return the symbolic name for a CKM_ mechanism."""
    return CKM_NAMES.get(mech, f"UNKNOWN(0x{mech:08X})")


def cko_name(cls: int) -> str:
    """Return the symbolic name for a CKO_ object class."""
    return CKO_NAMES.get(cls, f"UNKNOWN(0x{cls:08X})")


def ckk_name(key_type: int) -> str:
    """Return the symbolic name for a CKK_ key type."""
    return CKK_NAMES.get(key_type, f"UNKNOWN(0x{key_type:08X})")


def cks_name(state: int) -> str:
    """Return the symbolic name for a CKS_ key state."""
    return CKS_NAMES.get(state, f"UNKNOWN(0x{state:08X})")


class PKCS11Error(Exception):
    """Exception carrying a PKCS#11 return code."""

    def __init__(self, code: int, message: str = ""):
        self.code = code
        self.message = message or ckr_name(code)
        super().__init__(f"{ckr_name(code)} (0x{code:08X}): {self.message}")
